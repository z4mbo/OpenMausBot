import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const data = JSON.parse(await readFile("/tmp/origin-qa-session.json", "utf8"));
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  await context.addInitScript(token => localStorage.setItem("origin.sessionToken", token), data.alex.sessionToken);
  const page = await context.newPage();
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:3001/${data.workspace.slug}?project=${data.projectId}`);
  await page.locator(".task-card").first().waitFor();
  assert.equal(await page.locator(".sidebar-footer").count(), 0);
  assert.equal(await page.locator(".kanban-column").filter({ has: page.locator(".kanban-title strong", { hasText: /^Done$/ }) }).count(), 0);
  assert.equal(await page.locator(".project-header .crumb").count(), 0);
  const avatar = await page.locator(".profile-chip .avatar").boundingBox();
  assert.equal(Math.round(avatar.width), Math.round(avatar.height));
  const nav = await page.getByRole("button", { name: "Chat", exact: true }).boundingBox();
  await page.getByRole("button", { name: "Projects", exact: true }).click();
  assert.deepEqual(await page.getByRole("button", { name: "Chat", exact: true }).boundingBox(), nav);
  await page.getByRole("button", { name: "Projects", exact: true }).click();
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await page.getByPlaceholder("Search projects, issues, teammates").fill("Sam");
  await page.locator(".search-results button").filter({ hasText: /Sam$/ }).click();
  const profile = page.getByRole("dialog", { name: "Member profile" });
  await profile.getByRole("heading", { name: "Sam", exact: true }).waitFor();
  await profile.getByRole("button", { name: /Ship responsive navigation/ }).waitFor();
  await profile.getByRole("tab", { name: "Completed", exact: true }).click();
  await profile.getByText("No completed issues yet.").waitFor();
  await page.screenshot({ path: "/tmp/origin-member-profile-desktop.png" });
  await profile.getByRole("tab", { name: "To do", exact: true }).click();
  await profile.getByRole("button", { name: /Ship responsive navigation/ }).click();
  await page.locator(".issue-detail-dialog").waitFor();
  await page.keyboard.press("Escape");
  console.log("PASS circular avatar, stable sidebar, member search and issue navigation");
  await page.getByRole("button", { name: "Complete Ship responsive navigation", exact: true }).click();
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await page.getByPlaceholder("Search projects, issues, teammates").fill("Sam");
  await page.locator(".search-results button").filter({ hasText: /Sam$/ }).click();
  await profile.getByText("No issues to do. All clear.").waitFor();
  await profile.getByRole("tab", { name: "Completed", exact: true }).click();
  await profile.getByRole("button", { name: /Ship responsive navigation/ }).waitFor();
  await profile.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: /View .* completed issues in Todo/ }).click();
  await page.locator(".archive-row").filter({ hasText: "Ship responsive navigation" }).waitFor();
  await page.locator(".archive-row").filter({ hasText: "Ship responsive navigation" }).getByRole("button", { name: "Restore" }).click();
  await page.getByRole("button", { name: /^Active/ }).click();
  await page.locator(".task-card").filter({ hasText: "Ship responsive navigation" }).waitFor();
  await page.locator(".project-navigation").getByRole("button", { name: "Create issue" }).click();
  await page.getByRole("dialog", { name: "New issue" }).waitFor();
  await page.getByRole("button", { name: "Close dialog" }).click();
  assert.equal(await page.locator(".kanban-column input").count(), 0);
  console.log("PASS completed issues by column, restoration and header issue creation");
  await page.locator(".project-button").filter({ hasText: "Member project" }).click();
  await page.locator(".empty-lane").first().waitFor();
  const emptyColumn = await page.locator(".kanban-column").first().boundingBox();
  const emptyLane = await page.locator(".empty-lane").first().boundingBox();
  assert.ok(Math.abs(emptyColumn.y + emptyColumn.height - emptyLane.y - emptyLane.height) < 10, "empty issue border should reach the column bottom");
  await page.screenshot({ path: "/tmp/origin-empty-columns.png" });
  await page.locator(".project-button").filter({ hasText: "Website" }).click();
  await page.getByRole("button", { name: "Team", exact: true }).click();
  await page.getByRole("button", { name: "View Sam profile", exact: true }).click();
  await profile.getByRole("heading", { name: "Sam", exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/origin-member-profile-mobile.png" });
  assert.ok((await profile.boundingBox()).width <= 390);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await profile.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: "Open navigation" }).click();
  await page.getByRole("button", { name: "Chat", exact: true }).click();
  await page.locator(".conversation-message .chat-profile-avatar").first().click();
  await profile.waitFor();
  await profile.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: "Open navigation" }).click();
  await page.getByRole("combobox", { name: "Switch workspace" }).selectOption("__create");
  await page.getByRole("dialog", { name: "Create workspace" }).waitFor();
  await page.getByRole("button", { name: "Close dialog" }).click();
  console.log("PASS member list and chat profile entry points, mobile fit, workspace creation dialog");
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
