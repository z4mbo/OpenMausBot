import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { ConvexHttpClient } from "convex/browser";
import { makeFunctionReference } from "convex/server";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const data = JSON.parse(await readFile("/tmp/origin-qa-session.json", "utf8"));
const client = new ConvexHttpClient("http://127.0.0.1:3210");
const mutation = (name, args) => client.mutation(makeFunctionReference(name), args);
const query = (name, args) => client.query(makeFunctionReference(name), args);
const scope = { sessionToken: data.alex.sessionToken, projectId: data.projectId };
const url = `http://127.0.0.1:3001/${data.workspace.slug}?project=${data.projectId}`;
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
  await context.addInitScript(token => localStorage.setItem("origin.sessionToken", token), data.alex.sessionToken);
  const page = await context.newPage();
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(url);
  await page.locator(".task-card").first().waitFor();
  const names = () => page.locator(".sidebar-project-list .project-button > span:nth-child(2)").allTextContents();
  const sort = async name => { await page.getByRole("button", { name: "Sort projects" }).click(); await page.getByRole("menuitemradio", { name, exact: true }).click(); };
  await sort("Name A to Z");
  const alphabetical = await names();
  assert.deepEqual(alphabetical, [...alphabetical].sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base", numeric: true })));
  await page.reload();
  await page.locator(".task-card").first().waitFor();
  assert.deepEqual(await names(), alphabetical);
  await sort("Recently updated");
  await mutation("projects:update", { ...scope, description: "Recently updated sidebar QA" });
  await page.waitForFunction(() => document.querySelector(".sidebar-project-list .project-button > span:nth-child(2)")?.textContent === "Website");
  await page.getByRole("button", { name: "Sort projects" }).click();
  await page.screenshot({ path: "/tmp/origin-project-sort.png" });
  await page.keyboard.press("Escape");
  await sort("Custom order");
  const customOrder = await names();
  await sort("Name A to Z");
  await sort("Custom order");
  assert.deepEqual(await names(), customOrder, "display sorting must preserve custom ordering");
  const firstProject = page.locator(".sidebar-project-list .project-button").first();
  await firstProject.focus();
  await firstProject.press("Alt+ArrowDown");
  await page.waitForFunction(first => document.querySelector(".sidebar-project-list .project-button > span:nth-child(2)")?.textContent !== first, customOrder[0]);
  await page.reload();
  await page.locator(".task-card").first().waitFor();
  assert.deepEqual((await names()).slice(0, 2), [customOrder[1], customOrder[0]]);
  console.log("PASS #3 sort menu, recent activity and persisted alphabetical preference");

  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByLabel("Icon type").selectOption("icon");
  assert.ok(await page.locator(".icon-library-grid button").count() >= 50);
  await page.getByRole("searchbox", { name: "Search icons" }).fill("rocket");
  await page.getByRole("button", { name: "Rocket", exact: true }).click();
  await page.getByRole("button", { name: "Save project", exact: true }).click();
  const website = page.locator(".project-button").filter({ hasText: "Website" });
  await website.getByLabel("You are viewing this project").waitFor();
  assert.equal(await website.evaluate(element => getComputedStyle(element).boxShadow), "none");
  await website.locator(".lucide-rocket").waitFor();
  const emoji = "\u{1F469}\u{1F3FD}\u200D\u{1F4BB}";
  await page.getByLabel("Icon type").selectOption("emoji");
  await page.getByLabel("Emoji", { exact: true }).fill(emoji);
  await page.getByRole("button", { name: "Save project", exact: true }).click();
  await website.locator(".project-icon.emoji").waitFor();
  assert.equal(await website.locator(".project-icon.emoji").textContent(), emoji);
  await page.reload();
  await website.locator(".project-icon.emoji").waitFor();
  assert.equal(await website.locator(".project-icon.emoji").textContent(), emoji);
  console.log("PASS #3 searchable icon library, immediate sidebar icon updates and complex emoji after reload");

  const collaboratorContext = await browser.newContext();
  await collaboratorContext.addInitScript(token => localStorage.setItem("origin.sessionToken", token), data.sam.sessionToken);
  const collaborator = await collaboratorContext.newPage();
  collaborator.on("pageerror", error => errors.push(error.message));
  await collaborator.goto(url);
  await website.getByLabel("Sam is viewing this project").waitFor();
  assert.equal(await website.evaluate(element => getComputedStyle(element).boxShadow), "none", "presence is represented by avatars only");
  await page.screenshot({ path: "/tmp/origin-presence-desktop.png" });
  await collaborator.getByRole("button", { name: "Chat", exact: true }).click();
  await website.getByLabel("Sam is viewing this project").waitFor({ state: "detached" });
  await collaborator.locator(".project-button").filter({ hasText: "Mobile app" }).click();
  await page.locator(".project-button").filter({ hasText: "Mobile app" }).getByLabel("Sam is viewing this project").waitFor();
  await collaborator.getByRole("button", { name: "Chat", exact: true }).click();
  await collaboratorContext.close();
  console.log("PASS #2 two-user browser presence, project changes and leaving for chat");

  await page.locator(".project-navigation").getByRole("button", { name: "Create issue" }).click();
  const composer = page.getByRole("dialog", { name: "New issue", exact: true });
  assert.equal(await composer.getByText("Create another", { exact: true }).count(), 0);
  for (const label of ["Status", "Priority", "Assignee", "Due date"]) assert.equal(await composer.getByLabel(label, { exact: true }).getAttribute("required"), "");
  await composer.getByLabel("Issue title").fill("Required properties browser QA");
  await composer.getByRole("button", { name: "Create issue" }).click();
  assert.ok(await composer.isVisible());
  assert.equal(await composer.getByLabel("Assignee", { exact: true }).evaluate(element => element.validity.valueMissing), true);
  await composer.getByLabel("Assignee", { exact: true }).selectOption(data.alex.user.email);
  await composer.getByRole("button", { name: "Create issue" }).click();
  assert.equal(await composer.getByLabel("Due date", { exact: true }).evaluate(element => element.validity.valueMissing), true);
  await composer.getByLabel("Due date", { exact: true }).fill("2026-10-02");
  await page.screenshot({ path: "/tmp/origin-issue-composer-desktop.png" });
  await composer.getByRole("button", { name: "Create issue" }).click();
  await composer.waitFor({ state: "detached" });
  const card = page.locator(".task-card").filter({ hasText: "Required properties browser QA" });
  await card.click();
  const detail = page.locator(".issue-detail-dialog");
  await detail.getByLabel("Issue title").waitFor();
  await detail.getByLabel("Due date", { exact: true }).fill("2026-10-03");
  await detail.getByRole("button", { name: "Close dialog" }).click();
  await detail.waitFor({ state: "detached" });
  await card.click();
  assert.equal(await detail.getByLabel("Due date", { exact: true }).inputValue(), "2026-10-03", "closing immediately must flush pending edits");
  const longComment = `Ready for review.\n${"A-long-unbroken-comment-".repeat(25)}\nThe mobile layout is ready too.`;
  await detail.getByRole("textbox", { name: "Comment", exact: true }).fill(longComment);
  await detail.getByRole("button", { name: "Comment", exact: true }).click();
  await detail.locator(".issue-timeline-entry").filter({ hasText: "Ready for review" }).waitFor();
  await detail.getByRole("button", { name: "Attach a link" }).click();
  await detail.getByLabel("Name", { exact: true }).fill("Prototype and interaction notes");
  await detail.getByLabel("URL", { exact: true }).fill("https://example.com/prototype");
  await detail.getByRole("button", { name: "Attach", exact: true }).click();
  await detail.getByRole("link", { name: "Prototype and interaction notes" }).waitFor();
  const assertFits = async () => {
    const overflow = await detail.evaluate(root => [...root.querySelectorAll("input, select, textarea, .activity-entry-content, .issue-detail-sidebar")].filter(element => element.scrollWidth > element.clientWidth + 2 && !element.matches("input, textarea, select")).map(element => element.className));
    assert.deepEqual(overflow, []);
    const fields = await detail.locator(".issue-field-grid label").evaluateAll(elements => elements.map(element => { const box = element.getBoundingClientRect(); return { x: box.x, y: box.y, right: box.right, bottom: box.bottom }; }));
    for (let i = 0; i < fields.length; i++) for (let j = i + 1; j < fields.length; j++) {
      const a = fields[i], b = fields[j];
      assert.ok(a.right <= b.x || b.right <= a.x || a.bottom <= b.y || b.bottom <= a.y, "properties must not overlap");
    }
    assert.ok(await detail.evaluate(element => element.scrollWidth <= element.clientWidth + 1));
  };
  await assertFits();
  await detail.evaluate(element => element.scrollTo(0, 0));
  await page.screenshot({ path: "/tmp/origin-issue-detail-desktop.png" });
  for (const width of [768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await assertFits();
    if (width === 320) assert.ok((await detail.getByLabel("Due date", { exact: true }).boundingBox()).width > 220, "narrow screens need a full-width date field");
    await detail.evaluate(element => element.scrollTo(0, 0));
    await page.screenshot({ path: `/tmp/origin-issue-detail-${width}.png` });
    await detail.getByRole("textbox", { name: "Comment", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: `/tmp/origin-issue-comments-${width}.png` });
  }
  await detail.getByRole("button", { name: "Close dialog" }).click();
  await page.locator(".project-navigation").getByRole("button", { name: "Create issue" }).click();
  await composer.waitFor();
  await composer.getByLabel("Due date", { exact: true }).scrollIntoViewIfNeeded();
  assert.ok(await composer.evaluate(element => element.scrollWidth <= element.clientWidth + 1));
  await page.screenshot({ path: "/tmp/origin-issue-composer-mobile.png" });
  await composer.getByRole("button", { name: "Close dialog" }).click();
  console.log("PASS #4 and #5 required fields, save-on-close, comments, attachments, desktop/tablet/mobile layout without overlap");
  assert.deepEqual(errors, []);
  const created = (await query("tasks:board", scope)).tasks.find(task => task.title === "Required properties browser QA");
  if (created) await mutation("tasks:deleteTask", { ...scope, taskId: created._id });
} finally { await browser.close(); }
