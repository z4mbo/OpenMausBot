import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHmac } from "node:crypto";
import { ConvexHttpClient } from "convex/browser";
import { makeFunctionReference } from "convex/server";
import * as Y from "yjs";

process.loadEnvFile("/tmp/origin-integration-qa.env");
const url = process.env.NEXT_PUBLIC_CONVEX_URL;
assert.equal(new URL(url).hostname, "127.0.0.1", "Never test against production");
const client = new ConvexHttpClient(url, { logger: false });
const q = (name, args) => client.query(makeFunctionReference(name), args);
const m = (name, args) => client.mutation(makeFunctionReference(name), args);
const { alex, sam, viewer, workspace } = JSON.parse(await readFile("/tmp/origin-qa-session.json", "utf8"));
const scope = { sessionToken: alex.sessionToken, teamId: workspace._id };
const paginationOpts = { numItems: 10, cursor: null };
const id = await m("projects:create", { ...scope, name: `Launch QA ${Date.now()}` });
const project = { sessionToken: alex.sessionToken, projectId: id };
for (const person of [sam, viewer]) await m("members:addWorkspaceMember", { ...project, email: person.user.email, role: "member" });
const board = await q("tasks:board", project);
const taskId = await m("tasks:createTask", { ...project, columnId: board.columns[0]._id, title: "Ship launch workflow", priority: "high", assignedToEmail: alex.user.email, dueDate: "2026-10-01" });
const privateWorkspace = (await q("workspaces:list", { sessionToken: sam.sessionToken })).find(w => w._id !== workspace._id);
const foreign = { sessionToken: alex.sessionToken, teamId: privateWorkspace._id };

const pageId = await m("documents:create", { ...scope, projectId: id, title: "Product specification", type: "wiki", content: "Hello" });
const initial = await q("documents:get", { sessionToken: alex.sessionToken, pageId });
const one = new Y.Doc(); const two = new Y.Doc();
Y.applyUpdate(one, new Uint8Array(initial.collaborationState));
Y.applyUpdate(two, new Uint8Array(initial.collaborationState));
const updates = [];
one.on("update", update => updates.push({ sessionToken: alex.sessionToken, update }));
two.on("update", update => updates.push({ sessionToken: sam.sessionToken, update }));
one.getText("content").insert(5, " Alex"); two.getText("content").insert(0, "Sam ");
await Promise.all(updates.map(({ sessionToken, update }) => m("documents:applyUpdate", { sessionToken, pageId, update: new Uint8Array(update).buffer })));
const merged = await q("documents:get", { sessionToken: alex.sessionToken, pageId });
assert.equal(merged.content, "Sam Hello Alex");
await m("documents:applyUpdate", { sessionToken: alex.sessionToken, pageId, update: new Uint8Array(updates[0].update).buffer });
assert.equal((await q("documents:get", { sessionToken: alex.sessionToken, pageId })).content, merged.content);
await assert.rejects(m("documents:rename", { sessionToken: viewer.sessionToken, pageId, title: "Forbidden" }), /role/i);
await assert.rejects(q("documents:list", foreign), /access/i);
await m("wiki:update", { ...project, pageId, content: "Updated through project wiki" });
const wiki = await q("documents:get", { sessionToken: alex.sessionToken, pageId });
const check = new Y.Doc(); Y.applyUpdate(check, new Uint8Array(wiki.collaborationState));
assert.equal(check.getText("content").toString(), wiki.content);
assert.ok((await q("workspaceSearch:documents", { ...scope, text: "specification" })).some(d => d._id === pageId));
console.log("PASS documents: CRDT concurrent edits, idempotency, legacy consistency, search and access controls");

const milestoneId = await m("planning:saveMilestone", { ...scope, title: "Public beta", description: "Ready to launch", targetDate: "2026-10-01", status: "active" });
await m("planning:assignMilestone", { ...scope, taskId, milestoneId });
assert.ok((await q("planning:milestones", { ...scope, paginationOpts })).page.find(r => r._id === milestoneId).issues.some(t => t._id === taskId));
await assert.rejects(m("planning:saveMilestone", { ...scope, title: "Invalid date", description: "", targetDate: "2026-02-31", status: "planned" }), /date/i);
await assert.rejects(m("planning:assignMilestone", { ...scope, sessionToken: viewer.sessionToken, taskId, milestoneId }), /role/i);
await assert.rejects(q("planning:milestones", { ...foreign, paginationOpts }), /access/i);
const release = { ...scope, projectId: id, version: "v1.0.0", body: "Launch workflow", taskIds: [taskId], publish: true };
await assert.rejects(m("planning:saveRelease", release), /completed/i);
await m("tasks:updateTask", { ...project, taskId, done: true });
const releaseId = await m("planning:saveRelease", release);
const published = (await q("planning:releases", { ...scope, paginationOpts })).page.find(r => r._id === releaseId);
assert.ok(published.publishedAt); assert.equal(published.issues[0]._id, taskId);
await assert.rejects(m("planning:saveRelease", { ...release, sessionToken: viewer.sessionToken }), /role/i);
console.log("PASS roadmap and releases: workflow, dates, completed-only validation and permissions");

const slug = await m("feedback:configure", { ...scope, projectId: id, title: "Product feedback", description: "Share ideas", enabled: true });
assert.deepEqual(await q("feedback:publicPortal", { slug }), { title: "Product feedback", description: "Share ideas" });
const portal = (await q("feedback:portals", scope)).find(p => p.slug === slug);
const body = JSON.stringify({ at: Date.now(), operation: "feedback", args: { slug, title: "Keyboard navigation", body: "Add clearer keyboard focus", kind: "idea" } });
const submitted = await fetch(`${process.env.NEXT_PUBLIC_CONVEX_SITE_URL}/integrations`, { method: "POST", body, headers: { "x-origin-signature": createHmac("sha256", process.env.ORIGIN_INTEGRATION_SECRET).update(body).digest("hex") } });
assert.equal(submitted.status, 200, await submitted.text());
const entry = (await q("feedback:list", { ...scope, portalId: portal._id }))[0];
const convert = { ...scope, entryId: entry._id, columnId: board.columns[0]._id, assignedToEmail: alex.user.email, dueDate: "2026-10-01" };
await assert.rejects(m("feedback:convert", { ...convert, sessionToken: viewer.sessionToken }), /role/i);
const feedbackTask = await m("feedback:convert", convert);
assert.equal(await m("feedback:convert", convert), feedbackTask);
await m("tasks:updateTask", { ...project, taskId: feedbackTask, done: true });
assert.equal((await q("feedback:list", { ...scope, portalId: portal._id }))[0].status, "completed");
await assert.rejects(q("feedback:list", { ...foreign, portalId: portal._id }), /access/i);
await m("feedback:configure", { ...scope, projectId: id, title: "Product feedback", description: "Share ideas", enabled: false });
assert.equal(await q("feedback:publicPortal", { slug }), null);
console.log("PASS feedback: opt-in public fields only, signed submissions, issue conversion deduplication and completion sync");
for (const doc of [one, two, check]) doc.destroy();

const secondTask = await m("tasks:createTask", { ...project, columnId: board.columns[0]._id, title: "Review launch", priority: "medium", assignedToEmail: sam.user.email, dueDate: "2026-10-02" });
const relation = { sessionToken: alex.sessionToken, fromTaskId: taskId, toTaskId: secondTask, kind: "blocks" };
await m("issueRelations:connect", relation);
await m("issueRelations:connect", relation);
assert.equal((await q("issueRelations:list", { sessionToken: alex.sessionToken, taskId })).relations.length, 1);
await assert.rejects(m("issueRelations:connect", { ...relation, fromTaskId: secondTask, toTaskId: taskId }), /cycle/i);
await assert.rejects(m("issueRelations:connect", { ...relation, sessionToken: viewer.sessionToken }), /role/i);
await m("issueRelations:labels", { sessionToken: alex.sessionToken, taskId, labels: [" launch ", "launch", "urgent"] });
assert.deepEqual((await q("issueRelations:list", { sessionToken: alex.sessionToken, taskId })).labels, ["launch", "urgent"]);
console.log("PASS issue relationships: idempotency, cycle prevention, viewer protection and labels");

const calendar = { ...scope, start: "2026-10-01", end: "2026-10-31", mine: true };
assert.ok((await q("inbox:calendar", calendar)).tasks.some(t => t._id === taskId));
assert.ok(!(await q("inbox:calendar", calendar)).tasks.some(t => t._id === secondTask));
assert.ok((await q("inbox:calendar", { ...calendar, mine: false })).tasks.some(t => t._id === secondTask));
await assert.rejects(q("inbox:calendar", { ...calendar, start: "2026-02-31" }), /date/i);
await assert.rejects(q("inbox:calendar", { ...calendar, teamId: privateWorkspace._id }), /access/i);
console.log("PASS calendar: assigned-only default, workspace scoping and valid date ranges");

const samScope = { sessionToken: sam.sessionToken, teamId: workspace._id };
const defaults = await q("preferences:notifications", samScope);
await m("preferences:saveNotifications", { ...samScope, ...defaults, comments: false, quietStart: "22:00", quietEnd: "08:00", timeZone: "Europe/Rome" });
assert.equal((await q("preferences:notifications", samScope)).comments, false);
assert.equal((await q("preferences:notifications", scope)).comments, true);
await assert.rejects(m("preferences:saveNotifications", { ...samScope, ...defaults, quietStart: "25:00" }), /quiet/i);
const notification = (await q("notifications:list", { ...samScope, unreadOnly: false, paginationOpts })).page.find(n => n.taskId === secondTask);
assert.ok(notification);
const until = Date.now() + 86400000;
await m("notifications:snooze", { ...samScope, id: notification._id, until });
assert.equal((await q("notifications:list", { ...samScope, unreadOnly: false, paginationOpts })).page.find(n => n._id === notification._id).snoozedUntil, until);
await assert.rejects(m("notifications:markRead", { ...scope, id: notification._id, read: true }), /not found/i);
await m("notifications:markRead", { ...samScope, id: notification._id, read: true });
assert.equal((await q("notifications:list", { ...samScope, unreadOnly: false, paginationOpts })).page.find(n => n._id === notification._id).snoozedUntil, undefined);
await m("preferences:saveNotifications", { ...samScope, ...defaults });
console.log("PASS notification preferences and snoozing: per-user isolation, validation and cancellation");
