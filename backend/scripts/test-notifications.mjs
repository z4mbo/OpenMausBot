import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHmac } from "node:crypto";
import { ConvexHttpClient } from "convex/browser";
import { makeFunctionReference } from "convex/server";
process.loadEnvFile("/tmp/origin-integration-qa.env");
const site = process.env.ORIGIN_PUBLIC_URL;
assert.equal(new URL(site).hostname, "127.0.0.1");
assert.equal(new URL(process.env.NEXT_PUBLIC_CONVEX_URL).hostname, "127.0.0.1");
const { alex, sam, workspace } = JSON.parse(await readFile("/tmp/origin-qa-session.json", "utf8"));
const client = new ConvexHttpClient(process.env.NEXT_PUBLIC_CONVEX_URL, { logger: false });
const q = (name, args) => client.query(makeFunctionReference(name), args), m = (name, args) => client.mutation(makeFunctionReference(name), args);
const alexScope = { sessionToken: alex.sessionToken, teamId: workspace._id }, samScope = { ...alexScope, sessionToken: sam.sessionToken };
const projectId = await m("projects:create", { ...alexScope, name: "Notifications QA", repoUrl: "https://github.com/origin-local-tests/notifications" });
const scope = { sessionToken: alex.sessionToken, projectId };
const columnId = (await q("tasks:board", scope)).columns[0]._id;
const taskId = await m("tasks:createTask", { ...scope, columnId, title: "Notification test", priority: "high", assignedToEmail: sam.user.email, dueDate: "2026-10-01" });
const list = (scope, unreadOnly = true) => q("notifications:list", { ...scope, unreadOnly, paginationOpts: { cursor: null, numItems: 50 } });
let rows = (await list(samScope)).page;
assert.equal(rows.filter(n => n.taskId === taskId && n.kind === "assignment").length, 1);
assert.equal((await list(alexScope)).page.filter(n => n.taskId === taskId).length, 0, "No self notifications");
await m("tasks:updateTask", { ...scope, taskId, assignedToEmail: sam.user.email });
assert.equal((await list(samScope)).page.filter(n => n.taskId === taskId).length, 1, "Unchanged assignment must not notify");
await m("tasks:addComment", { ...scope, taskId, body: "Please review the responsive layout" });
rows = (await list(samScope)).page;
assert.equal(rows.filter(n => n.taskId === taskId && n.kind === "comment").length, 1);
const notification = rows.find(n => n.taskId === taskId && n.kind === "comment");
assert.match(notification.preview, /responsive/); assert.equal(notification.projectName, "Notifications QA");
await assert.rejects(m("notifications:markRead", { ...alexScope, id: notification._id, read: true }), /not found/);
await m("notifications:markRead", { ...samScope, id: notification._id, read: true });
assert.equal((await list(samScope)).page.some(n => n._id === notification._id), false);
await m("notifications:markRead", { ...samScope, id: notification._id, read: false });
assert.equal((await list(samScope)).page.some(n => n._id === notification._id), true);
const otherTeam = (await q("workspaces:list", { sessionToken: sam.sessionToken })).find(t => t._id !== workspace._id);
await assert.rejects(q("notifications:summary", { ...alexScope, teamId: otherTeam._id }), /access/);
console.log("PASS assignment/comment recipients, self exclusion, unchanged-assignment deduplication, unread state and workspace isolation");
const body = JSON.stringify({ at: Date.now(), operation: "chatMentions", args: { teamId: workspace._id, actorId: alex.user._id, messageId: `qa-${Date.now()}`, userIds: [sam.user._id] } });
const bridge = () => fetch(`${process.env.NEXT_PUBLIC_CONVEX_SITE_URL}/integrations`, { method: "POST", body, headers: { "x-origin-signature": createHmac("sha256", process.env.ORIGIN_INTEGRATION_SECRET).update(body).digest("hex") } });
assert.equal((await bridge()).ok, true); assert.equal((await bridge()).ok, true);
const messageId = JSON.parse(body).args.messageId;
assert.equal((await list(samScope)).page.filter(n => n.messageId === messageId).length, 1);
const chatPost = await fetch(`${site}/api/local-chat/messages?teamId=${workspace._id}`, { method: "POST", headers: { Authorization: `Bearer ${alex.sessionToken}`, "Content-Type": "application/json" }, body: JSON.stringify({ body: "Local mention regression", mentionUserIds: [sam.user._id] }) });
assert.equal(chatPost.ok, true, await chatPost.clone().text());
const { message } = await chatPost.json(); assert.equal(message.mentions[0].userId, sam.user._id);
for (let i = 0; i < 15; i++) { if ((await list(samScope)).page.some(n => n.messageId === message.id)) break; await new Promise(r => setTimeout(r, 200)); }
const mention = (await list(samScope)).page.find(n => n.messageId === message.id);
assert.ok(mention); assert.equal(mention.preview, undefined, "Chat content stays on Hetzner");
const focus = await fetch(`${site}/api/local-chat/messages?teamId=${workspace._id}&focus=${message.id}`, { headers: { Authorization: `Bearer ${sam.sessionToken}` } });
assert.equal(focus.ok, true); assert.ok((await focus.json()).messages.some(m => m.id === message.id));
const forbidden = await fetch(`${site}/api/local-chat/messages?teamId=${otherTeam._id}&focus=${message.id}`, { headers: { Authorization: `Bearer ${sam.sessionToken}` } }); assert.equal(forbidden.ok, false);
await m("notifications:markAll", samScope);
assert.equal((await q("notifications:summary", samScope)).unread, 0);
assert.ok((await list(samScope, false)).page.some(n => n.messageId === message.id));
console.log("PASS local chat mentions, metadata-only reliable delivery, duplicate delivery handling, deep links, isolation and mark all read");
