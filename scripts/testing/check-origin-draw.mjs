import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const url = new URL(process.argv[2] ?? "");
assert.equal(url.hostname, "127.0.0.1");
assert.equal(url.pathname, "/__origin-draw.html");
const output = resolve("docs/verification/evidence/origin-draw");
await mkdir(output, { recursive: true });
const { chromium } = await import(process.env.OMB_VERIFY_PLAYWRIGHT || "playwright");
const browser = await chromium.launch();
const evidence = { checkedAt: new Date().toISOString(), previewUrl: url.href, cases: [], pageErrors: [] };
try {
  for (const theme of ["light", "dark"]) for (const width of [375, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: "reduce" });
    page.on("pageerror", (error) => evidence.pageErrors.push(error.message));
    const target = new URL(url); target.searchParams.set("theme", theme);
    await page.goto(target.href);
    assert.equal(await page.title(), "Isolated Origin drawing");
    await page.waitForFunction(() => !!window.originDrawFixture);
    await page.getByRole("radio", { name: "Rectangle", exact: true }).waitFor();
    const capture = async (name) => {
      await page.waitForTimeout(180);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({ path: resolve(output, `${name}-${width}-${theme}.png`) });
    };
    const draw = async (offset = 0) => {
      await page.getByRole("radio", { name: "Rectangle", exact: true }).locator("..").click();
      const x = width === 375 ? 120 : 450;
      await page.mouse.move(x + offset, 320 + offset); await page.mouse.down();
      await page.mouse.move(x + offset + 110, 410 + offset, { steps: 5 }); await page.mouse.up();
    };
    const updates = () => page.evaluate(() => window.originDrawFixture.requests.filter(({ name }) => name === "draw:updateElements").length);
    await capture("after-empty");
    await draw();
    await page.waitForFunction(() => window.originDrawFixture.scene.length === 1);
    await capture("after-saved");
    const first = await updates();
    await page.evaluate(() => window.originDrawFixture.blockNextSave());
    await draw(20);
    await page.waitForFunction((count) => window.originDrawFixture.requests.filter(({ name }) => name === "draw:updateElements").length > count, first);
    await page.getByRole("button", { name: "Leave drawing", exact: true }).click();
    await page.evaluate(() => window.originDrawFixture.rejectSave());
    await page.waitForTimeout(100);
    await page.getByRole("button", { name: "Return to drawing", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "Synthetic offline save" }).waitFor();
    await capture("after-waiting-to-sync");
    await page.waitForFunction(() => window.originDrawFixture.scene.length === 2 && !Object.keys(localStorage).some((key) => key.startsWith("origin-drawing-outbox:")));
    await capture("after-navigation-recovery");
    const second = await updates();
    await page.evaluate(() => window.originDrawFixture.blockNextSave());
    await draw(40);
    await page.waitForFunction((count) => window.originDrawFixture.requests.filter(({ name }) => name === "draw:updateElements").length > count, second);
    await page.reload();
    assert.equal(await page.title(), "Isolated Origin drawing");
    await page.waitForFunction(() => window.originDrawFixture?.scene.length === 3 && !Object.keys(localStorage).some((key) => key.startsWith("origin-drawing-outbox:")));
    await capture("after-reload-recovery");
    const saved = await page.evaluate(() => window.originDrawFixture.scene.map((row) => { const { id, version, type } = JSON.parse(row); return { id, version, type }; }));
    target.searchParams.set("viewer", "1"); await page.goto(target.href);
    await page.getByText("View only", { exact: true }).waitFor();
    assert.equal(await page.getByRole("radio", { name: "Rectangle", exact: true }).count(), 0);
    await capture("after-viewer");
    evidence.cases.push({ theme, width, saved, navigationRecovery: true, reloadRecovery: true, viewerReadOnly: true, horizontalOverflow: false, reducedMotion: true });
    target.searchParams.delete("viewer"); target.searchParams.set("project", "1"); await page.goto(target.href);
    await page.getByRole("button", { name: "New canvas", exact: true }).waitFor();
    await capture("project-after");
    await page.getByRole("button", { name: "New canvas", exact: true }).click();
    await page.getByRole("textbox", { name: "Canvas name" }).fill("A new planning canvas");
    const create = await page.getByRole("button", { name: "Create", exact: true }).boundingBox();
    const ask = await page.getByRole("button", { name: "Ask Atlas", exact: true }).boundingBox();
    assert.ok(create && ask);
    assert.ok(create.x + create.width <= ask.x || ask.x + ask.width <= create.x || create.y + create.height <= ask.y || ask.y + ask.height <= create.y);
    await capture("project-new-after");
    await page.getByRole("button", { name: "Create", exact: true }).click();
    await page.getByRole("tab", { name: "A new planning canvas", exact: true }).waitFor();
    assert.equal(await page.getByRole("tab", { name: "A new planning canvas", exact: true }).getAttribute("aria-selected"), "true");
    await page.getByRole("button", { name: "Ask Atlas", exact: true }).click();
    await page.getByRole("textbox", { name: "Question", exact: true }).waitFor();
    await capture("project-ask-after");
    await page.getByRole("textbox", { name: "Question", exact: true }).press("Escape");
    assert.equal(await page.getByRole("textbox", { name: "Question", exact: true }).count(), 0);
    assert.equal(await page.getByRole("button", { name: "Ask Atlas", exact: true }).evaluate((element) => element === document.activeElement), true);
    evidence.cases.at(-1).projectCanvasCreateAndAsk = true;
    await page.close();
  }
  assert.deepEqual(evidence.pageErrors, []);
  await writeFile(resolve(output, "browser-checks.json"), JSON.stringify(evidence, null, 2) + "\n");
  console.log(JSON.stringify(evidence));
} finally { await browser.close(); }
